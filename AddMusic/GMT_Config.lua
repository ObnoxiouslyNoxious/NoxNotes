local function GMT_dprintFormat(fmt, ...)
	if select("#", ...) == 0 then
		return tostring(fmt)
	end
	return string.format(fmt, ...)
end

function GMT_warn(fmt, ...)
	print("[GMT][WARNING]", GMT_dprintFormat(fmt, ...))
end

local warnedOnce = {}

function GMT_warnOnce(fmt, ...)
	local message = GMT_dprintFormat(fmt, ...)
	if warnedOnce[message] then
		return
	end
	warnedOnce[message] = true
	print("[GMT][WARNING]", message)
end

function GMT_dprint(first, ...)
	if not (GMT_Config.DEBUG) then
		return
	end
	if type(first) == "string" and string.find(first, "^%[[%[%]A-Z0-9_]*%]$") then
		print("[GMT][DEBUG]" .. first, GMT_dprintFormat(...))
	else
		print("[GMT][DEBUG]", GMT_dprintFormat(first, ...))
	end
end
